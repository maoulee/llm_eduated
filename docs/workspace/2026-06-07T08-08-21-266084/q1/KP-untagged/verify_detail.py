"""精确验证每个子问题的平衡因子计算"""

# 平衡因子定义：BF = 左子树高度 - 右子树高度

# 子问题(1): 插入10, 15, 5, 12后
# 树结构：
#        10
#       /  \
#      5    15
#          /
#         12

print("=" * 60)
print("子问题(1) 精确验证")
print("=" * 60)

# 高度计算
h_12 = 1
h_15 = 1 + max(h_12, 0)  # 左子树高1(节点12), 右子树高0
h_5 = 1
h_10 = 1 + max(h_5, h_15)  # 左子树高1(节点5), 右子树高2(节点15)

print(f"高度: h(12)={h_12}, h(15)={h_15}, h(5)={h_5}, h(10)={h_10}")

# 平衡因子计算
bf_12 = 0 - 0  # 叶子节点
bf_15 = 1 - 0  # 左子树高1, 右子树高0
bf_5 = 0 - 0   # 叶子节点
bf_10 = 1 - 2  # 左子树高1, 右子树高2

print(f"BF(12)={bf_12}, BF(15)={bf_15}, BF(5)={bf_5}, BF(10)={bf_10}")
print(f"\nSolution声称: BF(10)=0, BF(15)=-1")
print(f"正确值: BF(10)={bf_10}, BF(15)={bf_15}")
print(f"Solution是否正确? BF(10): {'✓' if bf_10 == 0 else '✗'}, BF(15): {'✓' if bf_15 == -1 else '✗'}")

