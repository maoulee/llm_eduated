# -*- coding: utf-8 -*-
"""
存储器扩展设计题 —— 建模码
把题干参数 + 5 条场景规则翻译成代码，底部 print 完整数据流。
所有数值由代码计算，不脑内算。
"""
import math

# ========== PARAMS（题干注入参数）==========
PARAMS = {
    "CPU地址总线宽度": 16,        # A0~A15
    "CPU数据总线宽度": 8,          # D0~D7
    "编址方式": "字节编址",        # 每地址1字节
    "目标字数": 32 * 1024,         # 32K = 32768 个存储单元
    "目标字长": 8,                 # 位
    "芯片字数": 4 * 1024,          # 4K = 4096
    "芯片字长": 4,                 # 位
    "译码器类型": "3-8译码器",
}

# ========== 场景规则 2：扩展方式非平凡 ==========
位扩展系数 = PARAMS["目标字长"] // PARAMS["芯片字长"]      # 8/4 = 2
字扩展系数 = PARAMS["目标字数"] // PARAMS["芯片字数"]      # 32K/4K = 8

assert 位扩展系数 >= 2, "RULE2 FAIL: 位扩展系数<2，未强制位扩展"
assert 字扩展系数 >= 2, "RULE2 FAIL: 字扩展系数<2，未强制字扩展"
扩展方式 = "字位同时扩展"  # 既需要位扩展又需要字扩展

# ========== 场景规则 1：芯片数量守恒 ==========
每组芯片数 = 位扩展系数           # 位扩展方向
组数 = 字扩展系数                 # 字扩展方向
总芯片数 = 每组芯片数 * 组数
assert 总芯片数 == 位扩展系数 * 字扩展系数, "RULE1 FAIL: 芯片数守恒不成立"

# ========== 场景规则 3：地址位数守恒 ==========
片内地址位数 = int(math.log2(PARAMS["芯片字数"]))   # log2(4096) = 12
片选地址位数 = int(math.log2(PARAMS["目标字数"])) - 片内地址位数  # 15 - 12 = 3
目标地址位数 = int(math.log2(PARAMS["目标字数"]))   # log2(32768) = 15

assert 片内地址位数 == math.log2(PARAMS["芯片字数"]), "RULE3 FAIL: 片内地址位数 != log2(芯片字数)"
assert 片内地址位数 + 片选地址位数 == math.log2(PARAMS["目标字数"]), "RULE3 FAIL: 片内+片选 != log2(目标字数)"
assert math.log2(PARAMS["目标字数"]) <= PARAMS["CPU地址总线宽度"], "RULE3 FAIL: 目标容量超过CPU可寻址空间"

# 剩余地址线
使用地址位数 = 目标地址位数               # 15
剩余地址位数 = PARAMS["CPU地址总线宽度"] - 使用地址位数   # 16 - 15 = 1

# 地址线标号分配
# A0 ~ A(片内地址位数-1)  => 片内地址线
# A(片内地址位数) ~ A(目标地址位数-1) => 片选地址线
# A(目标地址位数) ~ A(CPU地址总线宽度-1) => 剩余未使用
片内地址线范围 = f"A0 ~ A{片内地址位数 - 1}"
片选地址线范围 = f"A{片内地址位数} ~ A{目标地址位数 - 1}"
剩余地址线标号 = [f"A{i}" for i in range(目标地址位数, PARAMS["CPU地址总线宽度"])]

# ========== 场景规则 4：地址范围连续且不重叠 ==========
芯片字数 = PARAMS["芯片字数"]
地址范围表 = []
for i in range(组数):
    start = i * 芯片字数
    end = (i + 1) * 芯片字数 - 1
    地址范围表.append({
        "组号": i,
        "起始地址_十进制": start,
        "结束地址_十进制": end,
        "起始地址_十六进制": f"0x{start:04X}",
        "结束地址_十六进制": f"0x{end:04X}",
    })

# 验证连续不重叠
for i in range(len(地址范围表)):
    start = i * 芯片字数
    end = (i + 1) * 芯片字数 - 1
    assert 地址范围表[i]["起始地址_十进制"] == start, "RULE4 FAIL: 第i组起始地址 != i*芯片字数"
    assert 地址范围表[i]["结束地址_十进制"] == end, "RULE4 FAIL: 第i组结束地址 != (i+1)*芯片字数-1"
    if i > 0:
        # 相邻组首尾相接无间隙
        assert 地址范围表[i]["起始地址_十进制"] == 地址范围表[i-1]["结束地址_十进制"] + 1, \
            "RULE4 FAIL: 相邻组不连续"

# ========== 场景规则 5：片选逻辑覆盖全部组 ==========
片选组合数 = 2 ** 片选地址位数
assert 片选组合数 >= 组数, "RULE5 FAIL: 2^片选地址位数 < 组数"
# 3-8译码器输入端连接：A12, A13, A14
译码器输入 = ["A12", "A13", "A14"]
片选信号表 = []
for i in range(组数):
    code = i  # 0~7 对应 A14 A13 A12 的二进制
    a14 = (code >> 2) & 1
    a13 = (code >> 1) & 1
    a12 = code & 1
    片选信号表.append({
        "组号": i,
        "译码器输出": f"Y{i}",
        "片选表达式": f"CS{i}_ = Y{i}_  (低有效)",
        "有效条件": f"A14 A13 A12 = {a14}{a13}{a12}",
        "地址范围": f"{地址范围表[i]['起始地址_十六进制']} ~ {地址范围表[i]['结束地址_十六进制']}",
    })
# 验证每组对应唯一片选地址组合
seen = set()
for item in 片选信号表:
    assert item["有效条件"] not in seen, "RULE5 FAIL: 多组共享同一片选地址组合"
    seen.add(item["有效条件"])

# ========== 底部：打印完整数据流 ==========
print("=" * 70)
print("PARAMS:")
for k, v in PARAMS.items():
    print(f"  {k}: {v}")

print("-" * 70)
print("PROCESS / 中间值:")
print(f"  位扩展系数 (目标字长/芯片字长) = {PARAMS['目标字长']}/{PARAMS['芯片字长']} = {位扩展系数}")
print(f"  字扩展系数 (目标字数/芯片字数) = {PARAMS['目标字数']}/{PARAMS['芯片字数']} = {字扩展系数}")
print(f"  扩展方式判定: 位扩展系数={位扩展系数}(>=2) 且 字扩展系数={字扩展系数}(>=2) → {扩展方式}")
print(f"  每组芯片数 (位扩展方向) = {每组芯片数}")
print(f"  组数 (字扩展方向) = {组数}")
print(f"  总芯片数 = 每组芯片数 × 组数 = {每组芯片数} × {组数} = {总芯片数}")
print(f"  片内地址位数 = log2({PARAMS['芯片字数']}) = {片内地址位数}")
print(f"  目标地址位数 = log2({PARAMS['目标字数']}) = {目标地址位数}")
print(f"  片选地址位数 = {目标地址位数} - {片内地址位数} = {片选地址位数}")
print(f"  剩余地址位数 = {PARAMS['CPU地址总线宽度']} - {使用地址位数} = {剩余地址位数}")
print(f"  片内地址线范围: {片内地址线范围}")
print(f"  片选地址线范围: {片选地址线范围}")
print(f"  剩余未使用地址线: {剩余地址线标号}")

print("-" * 70)
print("RESULT — 地址范围表（场景规则4: 连续不重叠）:")
print(f"  {'组号':>4}  {'起始地址':>8}  {'结束地址':>8}")
for row in 地址范围表:
    print(f"  {row['组号']:>4}  {row['起始地址_十六进制']:>8}  {row['结束地址_十六进制']:>8}")

print("-" * 70)
print("RESULT — 片选信号逻辑表达式（场景规则5: 覆盖全部组）:")
for item in 片选信号表:
    print(f"  CS{item['组号']}_: {item['片选表达式']}, 当 {item['有效条件']} 时有效, 覆盖地址 {item['地址范围']}")

print("-" * 70)
print("RULE_CHECK（5条场景规则验证）:")
print(f"  RULE1 芯片数量守恒: 总芯片数={总芯片数} == 位扩展×字扩展={位扩展系数}×{字扩展系数}={位扩展系数*字扩展系数} → {总芯片数 == 位扩展系数*字扩展系数}")
print(f"  RULE2 扩展方式非平凡: 位扩展系数={位扩展系数}>=2 且 字扩展系数={字扩展系数}>=2 → {扩展方式} → {位扩展系数>=2 and 字扩展系数>=2}")
print(f"  RULE3 地址位数守恒: 片内={片内地址位数}, 片选={片选地址位数}, 和={片内地址位数+片选地址位数}==log2(目标字数)={目标地址位数} → {片内地址位数+片选地址位数==目标地址位数}")
print(f"         log2(目标字数)={目标地址位数} <= CPU地址总线宽度={PARAMS['CPU地址总线宽度']} → {目标地址位数<=PARAMS['CPU地址总线宽度']}")
首尾连续 = all(地址范围表[i]["起始地址_十进制"] == 地址范围表[i-1]["结束地址_十进制"] + 1 for i in range(1, len(地址范围表)))
print(f"  RULE4 地址范围连续不重叠: {首尾连续}")
print(f"  RULE5 片选覆盖全部组: 2^{片选地址位数}={片选组合数} >= 组数={组数} → {片选组合数>=组数}, 每组唯一组合 → {len(seen)==组数}")
print("=" * 70)
