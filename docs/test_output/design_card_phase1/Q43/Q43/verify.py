R1 = 0x0001
R2 = 0x7FFF
MASK = (1 << WORD_SIZE) - 1  # 16位掩码 FFFF

# ===== 校验1：参数封闭性 =====
# 所有子问题所需参数：R1, R2, 字长
# 题干已给出 R1=0001H, R2=7FFFH, 字长=16位
# ✓ 参数封闭

# ===== 校验2：参数范围合法性 =====
assert 0 <= R1 <= MASK, f"R1={R1:#06X} 超出16位范围"
assert 0 <= R2 <= MASK, f"R2={R2:#06X} 超出16位范围"
print(f"R1 = {R1:#06X}H = {R1} (十进制)")
print(f"R2 = {R2:#06X}H = {R2} (十进制)")

