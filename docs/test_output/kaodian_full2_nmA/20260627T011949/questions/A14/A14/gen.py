"""
扩展操作码各级指令最大条数计算
题干规则逐句翻译为代码，底部 print 完整数据流，场景规则翻译为 assert。
"""

def solve(L, W, N3):
    """
    L  = 指令字长（位）
    W  = 地址码字段宽度（位）
    N3 = 三地址指令已定义条数
    返回各级操作码位宽、预留编码数、最大条数。
    """
    # ---- 各级地址数（从高到低）----
    levels = [3, 2, 1, 0]  # 三地址→二地址→一地址→零地址
    level_names = ["三地址", "二地址", "一地址", "零地址"]

    info = {}

    # ---- 第 1 级：三地址 ----
    k3 = 3
    opw3 = L - k3 * W          # 规则2：操作码位宽 = L - 地址数*W
    total3 = 2 ** opw3          # 该级操作码字段总编码数
    reserved3 = total3 - N3     # 规则3：预留编码数 = 总编码数 - 已定义数
    # 三地址已定义 14 条，为使最大条数→恰好保留 1 个前缀
    max3 = N3                   # 三地址实际条数 = 给定的 N3
    info["三地址"] = {
        "地址数": k3, "操作码位宽": opw3, "总编码数": total3,
        "已定义条数": N3, "预留编码数": reserved3, "本级最大条数": max3,
    }

    # ---- 第 2 级：二地址 ----
    k2 = 2
    opw2 = L - k2 * W
    # 规则4：下一级总编码数 = 上级预留数 × 2^W
    total2 = reserved3 * (2 ** W)
    # 规则5：非最后级最大条数 = 总编码数 - 1（保留 1 个前缀给下一级）
    max2 = total2 - 1
    reserved2 = 1  # 恰好保留 1 个
    info["二地址"] = {
        "地址数": k2, "操作码位宽": opw2, "总编码数": total2,
        "预留编码数": reserved2, "本级最大条数": max2,
    }

    # ---- 第 3 级：一地址 ----
    k1 = 1
    opw1 = L - k1 * W
    total1 = reserved2 * (2 ** W)
    max1 = total1 - 1
    reserved1 = 1
    info["一地址"] = {
        "地址数": k1, "操作码位宽": opw1, "总编码数": total1,
        "预留编码数": reserved1, "本级最大条数": max1,
    }

    # ---- 第 4 级：零地址（最后一级，不保留前缀）----
    k0 = 0
    opw0 = L - k0 * W
    total0 = reserved1 * (2 ** W)
    # 规则5：零地址 = 最后一级，最大条数 = 总编码数（不需保留）
    max0 = total0
    info["零地址"] = {
        "地址数": k0, "操作码位宽": opw0, "总编码数": total0,
        "本级最大条数": max0,
    }

    return info, (opw3, reserved3, max2, max1, opw0, max0)


# ============ 注入题干参数 ============
L = 16
W = 4
N3 = 14

info, (opw3, reserved3, max2, max1, opw0, max0) = solve(L, W, N3)

# ============ 底部：打印完整数据流 ============
print("=" * 60)
print("PARAMS:")
print(f"  L = {L}（指令字长，位）")
print(f"  W = {W}（地址码字段宽度，位）")
print(f"  N3 = {N3}（三地址指令已定义条数）")
print("=" * 60)

print("PROCESS（逐级推导）:")
print("-" * 60)

# 三地址
d3 = info["三地址"]
print(f"【三地址】地址数={d3['地址数']}")
print(f"  操作码位宽 = L - 3*W = {L} - 3*{W} = {d3['操作码位宽']} 位")
print(f"  操作码总编码数 = 2^{d3['操作码位宽']} = {d3['总编码数']}")
print(f"  已定义三地址指令 = {d3['已定义条数']} 条")
print(f"  预留编码数 = {d3['总编码数']} - {d3['已定义条数']} = {d3['预留编码数']}")
print()

# 二地址
d2 = info["二地址"]
print(f"【二地址】地址数={d2['地址数']}")
print(f"  操作码位宽 = L - 2*W = {L} - 2*{W} = {d2['操作码位宽']} 位")
print(f"  总编码数 = 三地址预留数 × 2^W = {d3['预留编码数']} × {2**W} = {d2['总编码数']}")
print(f"  最大条数 = {d2['总编码数']} - 1（保留1个前缀）= {d2['本级最大条数']} 条")
print()

# 一地址
d1 = info["一地址"]
print(f"【一地址】地址数={d1['地址数']}")
print(f"  操作码位宽 = L - 1*W = {L} - 1*{W} = {d1['操作码位宽']} 位")
print(f"  总编码数 = 二地址预留数 × 2^W = {d2['预留编码数']} × {2**W} = {d1['总编码数']}")
print(f"  最大条数 = {d1['总编码数']} - 1（保留1个前缀）= {d1['本级最大条数']} 条")
print()

# 零地址
d0 = info["零地址"]
print(f"【零地址】地址数={d0['地址数']}")
print(f"  操作码位宽 = L - 0*W = {L} - 0 = {d0['操作码位宽']} 位")
print(f"  总编码数 = 一地址预留数 × 2^W = {d1['预留编码数']} × {2**W} = {d0['总编码数']}")
print(f"  最大条数 = {d0['总编码数']}（最后一级，不保留前缀）= {d0['本级最大条数']} 条")
print("=" * 60)

print("RESULT:")
print(f"  Q1: 三地址操作码位宽 = {opw3} 位；预留编码数 = {reserved3} 个")
print(f"  Q2: 二地址最多 {max2} 条；一地址最多 {max1} 条")
print(f"  Q3: 零地址操作码位宽 = {opw0} 位；零地址最多 {max0} 条")
print("=" * 60)

# ============ 场景规则 → assert（通过条件翻译）============
# 规则1：L >= 3*W
assert L - 3 * W >= 1, f"规则1违反: L-3*W = {L - 3*W} < 1"

# 规则2：各级操作码位宽 = L - k*W，均 >= 1
for name, k in [("三地址",3),("二地址",2),("一地址",1),("零地址",0)]:
    w = L - k * W
    assert w >= 1, f"规则2违反: {name}操作码位宽 = {w} < 1"
    assert w == info[name]["操作码位宽"], f"规则2违反: {name}位宽不一致"

# 规则3：非最后级预留编码数 >= 1
assert (2 ** opw3) - N3 >= 1, f"规则3违反: 三地址预留 = {(2**opw3)-N3} < 1"
assert d2["预留编码数"] >= 1, f"规则3违反: 二地址预留 = {d2['预留编码数']} < 1"
assert d1["预留编码数"] >= 1, f"规则3违反: 一地址预留 = {d1['预留编码数']} < 1"

# 规则4：下一级总编码数 = 上级预留数 × 2^W
assert d2["总编码数"] == d3["预留编码数"] * (2 ** W), "规则4违反: 二地址总编码数"
assert d1["总编码数"] == d2["预留编码数"] * (2 ** W), "规则4违反: 一地址总编码数"
assert d0["总编码数"] == d1["预留编码数"] * (2 ** W), "规则4违反: 零地址总编码数"

# 规则5：非最后级 max = total - 1；零地址 max = total
assert d2["本级最大条数"] == d2["总编码数"] - 1, "规则5违反: 二地址"
assert d1["本级最大条数"] == d1["总编码数"] - 1, "规则5违反: 一地址"
assert d0["本级最大条数"] == d0["总编码数"], "规则5违反: 零地址"

# 规则6：零地址最大条数 = 最后保留前缀数 × 2^W，且 > 1
assert d0["本级最大条数"] == d1["预留编码数"] * (2 ** W), "规则6违反: 零地址=保留前缀×2^W"
assert d0["本级最大条数"] > 1, f"规则6违反: 零地址条数 = {d0['本级最大条数']} <= 1（平凡）"

print("\n所有场景规则 assert 通过 ✓")
