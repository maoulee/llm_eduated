from fractions import Fraction

x = Fraction(1, 2)
y = Fraction(-5, 8)

# Booth 算法的数学本质：
# y = -0.625 = -5/8
# y的补码 = 1.0110
# Booth递归: 
#   乘数从低位到高位: 0,1,1,0,1(符号)
#   附加位初始=0
#   判断对: (y0, extra0)=(0,0)→+0
#   (y1, y0)=(1,0)→-x
#   (y2, y1)=(1,1)→+0
#   (y3, y2)=(0,1)→+x
#   (ysign, y3)=(1,0)→-x  ← 第5趟！

# 等等！标准Booth是看 yi 和 y(i-1) 的关系
# 乘数 y = y4.y3 y2 y1 y0 (y4=符号)
# 附加位 y(-1) = 0
# 
# 判断对从低位到高位：
# (y0, y-1) = (0, 0) → 00 → +0
# (y1, y0)  = (1, 0) → 10 → -x
# (y2, y1)  = (1, 1) → 11 → +0
# (y3, y2)  = (0, 1) → 01 → +x
# (y4, y3)  = (1, 0) → 10 → -x  ← 需要第5步处理符号位！

# 所以标准Booth对5位乘数(含符号)需要5次判断！
# 但第5次判断后不移位（因为符号位不需要再移）

# 等等，题干说"5趟，第5趟仅移位不加减"
# 这意味着第5趟的判断和加减已经在第4趟完成后，
# 第5趟只是移位？这不对...

# 或者说题干的意思是：5趟都移位，但前4趟有加减判断，第5趟跳过加减只移位？
# 但标准Booth第5趟应该有判断(符号位参与)然后移位

# 关键：标准Booth n+1=5位乘数 → 5次(判断+加减+移位)，但最后一次不移位
# 或者：n+1次判断加减，n次移位

# 让我试: 5次判断+加减，但只移位4次
print("=== 方案: 5次判断加减，4次移位 ===")
X = Fraction(1,2)
NEG_X = Fraction(-1,2)

# 乘数位（含符号），从高位到低位: 1 0 1 1 0
# 附加位=0
y_bits = [1, 0, 1, 1, 0]  # y4 y3 y2 y1 y0 = 1 0 1 1 0
extra_init = 0

pp = Fraction(0)
prev = extra_init
print(f"初始 PP={pp}")
for i in range(5):
    curr = y_bits[4 - i]  # 从y0开始: y0,y1,y2,y3,y4
    pair = (curr, prev)
    if pair == (0, 1):
        pp += X
        op = f"+x={X}"
    elif pair == (1, 0):
        pp += NEG_X
        op = f"+(-x)={NEG_X}"
    else:
        op = "+0"
    print(f"  步{i+1}: yi={curr}, yi-1={prev}, pair={pair}, {op}, PP加减后={pp}")
    if i < 4:  # 前4次移位
        pp /= 2
        print(f"    右移后 PP={pp}")
    prev = curr

print(f"最终PP = {pp} = {float(pp)}")
print(f"期望 x*y = {x*y} = {float(x*y)}")
print(f"PP == x*y? {pp == x*y}")

# 试5次判断+加减，5次移位
print("\n=== 方案: 5次判断加减，5次移位 ===")
pp = Fraction(0)
prev = extra_init
for i in range(5):
    curr = y_bits[4 - i]
    pair = (curr, prev)
    if pair == (0, 1):
        pp += X
    elif pair == (1, 0):
        pp += NEG_X
    pp /= 2  # 每次都移位
    prev = curr
print(f"最终PP = {pp} = {float(pp)}")
print(f"PP == x*y? {pp == x*y}")

# 试4次判断加减，4次移位（不处理符号位单独那步）
print("\n=== 方案: 4次判断加减，4次移位 ===")
