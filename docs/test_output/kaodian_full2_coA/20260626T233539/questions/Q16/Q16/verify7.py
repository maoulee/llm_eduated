# 被乘数x（n+1位含符号），乘数y（n+1位含符号）
# 乘积2(n+1)位 = 2*5 = 10位
# 
# 乘积 = 部分积寄存器(高位) || 乘数寄存器(低位)
# 部分积用双符号位，所以部分积是n+2位=6位
# 乘数是n+1位=5位
# 总共 6+5=11位，但乘积只需2(n+1)=10位
# 所以取部分积的低n+1=5位(含1个符号位) + 乘数的n+1=5位 = 10位
#
# 部分积双符号位的最高位是冗余的（用于检测溢出），取低5位作为乘积高位
#
# 但是！部分积做了n+1=5次判断还是n=4次？
# 如果做n=4次移位：部分积右移4次，低5位=有效结果+符号
# 乘数右移4次后，低5位是乘数的高5位(逐渐被部分积移入的位填充)

# 关键问题：Booth算法标准做多少步？
# 参考标准教材：
# 对于n+1位乘数(含符号位)，Booth算法做n+1步
# 每步：判断+加减+(算术右移)
# 最后一步也右移
# 但最后一步移位后，部分积的符号位正确扩展
# 乘积 = 部分积(n+2位双符号, 取低n+1位) || 乘数(n+1位) = 2(n+1)位

# 所以：做5步(判断+加减+右移)，乘积取10位

# 但我们验证了5步的结果PP=11.1101, MQ=10000
# 乘积10位 = PP低5位 || MQ5位 = 11101 || 10000 = 1110110000
# 解码 = -5/32, 不是-5/16

# 问题一定在移位次数上！
# 如果做n=4步(判断+加减+右移):
# PP=00.0011, MQ=00001
# 乘积 = 00011 || 00001 = 0001100001 = 97/512 ≠ -5/16

# 两者都不对！这很奇怪。

# 让我用Python直接验证Booth算法的正确性
# 用整数运算，不关心位数

def booth_exact(x, y, n):
    """x,y为Fraction真值，n为数值位数(不含符号)
    返回乘积的Fraction真值"""
    # 这只是验证 x*y，不是模拟Booth
    return x * y

# 标准Booth：n=4数值位
# x=1/2, y=-5/8
# x*y = -5/16

# 用位级模拟，5位乘数，做不同的步数
# 找到哪种步数+拼接方式能得到-5/16

x_dbl = 0b001000  # 00.1000 = +1/2
neg_x_dbl = 0b111000  # 11.1000 = -1/2
y_5 = 0b10110  # 1.0110 = -5/8

# 尝试所有可能的步数和拼接方式
for n_steps in range(1, 8):
    for last_shift in [True, False]:
        combo = (0 << 5) | y_5
        extra = 0
        valid = True
        
        for i in range(n_steps):
            mq = combo % 32
            pp = combo >> 5
            mq_lsb = mq & 1
            judge = mq_lsb * 2 + extra
            
            if judge == 1:
                pp_new = (pp + x_dbl) % 64
            elif judge == 2:
                pp_new = (pp + neg_x_dbl) % 64
            else:
                pp_new = pp
            
            combo_after = (pp_new << 5) | mq
            new_extra = combo_after & 1
            
            do_shift = last_shift if i == n_steps - 1 else True
            if do_shift:
                sign = (combo_after >> 10) & 1
                combo = (combo_after >> 1) | (sign << 10)
                combo %= (1 << 11)
                extra = new_extra
            else:
                combo = combo_after
                extra = new_extra
        
        pp_f = combo >> 5
        mq_f = combo % 32
        
        # 拼接方式1: PP低5位 || MQ 5位
        p1 = ((pp_f & 0b011111) << 5) | mq_f
        # 拼接方式2: PP 6位 || MQ低4位
        p2 = ((pp_f & 0b111111) << 4) | ((mq_f >> 1) & 0b1111)
        # 拼接方式3: PP低5位 || MQ高4位+1位(全5位不对)
        # 拼接方式4: PP 6位 || MQ 5位 = 11位, 去掉最高位
        p4 = ((pp_f << 5) | mq_f) & 0b01111111111
        
        for pname, p in [("PP低5||MQ5", p1), ("PP6||MQ高4", p2), ("11位去最高", p4)]:
            pv = p % 1024
            if pv >= 512: pv -= 1024
            val = Fraction(pv, 512)
            if val == Fraction(-5, 16):
                print(f"✓ FOUND! steps={n_steps}, last_shift={last_shift}, {pname}: {format(p,'010b')} = {val}")

